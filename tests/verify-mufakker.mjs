const near = (a, b) => Math.abs(a - b) < 1e-6;
const num = t => {
  const s = String(t).replace(/\[\[|\]\]/g, '').replace('−', '-').replace(/^صفر$/, '0');
  const m = s.match(/-?\d+(?:\.\d+)?(?:\/\d+)?/);
  if (!m) return NaN;
  if (m[0].includes('/')) { const [a, b] = m[0].split('/').map(Number); return a / b; }
  return Number(m[0]);
};
const ratio = t => { const [a, b] = String(t).split(':').map(Number); return a / b; };

