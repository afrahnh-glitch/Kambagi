let n = 0;
for (const [p, key] of Object.entries(fileKey)) {
  const q = qs[id(p)];
  assert.ok(q, 'سؤال مفقود P' + p);
  assert.equal(q.status, 'verified', 'P' + p);
  assert.equal(q.answer, L[key], `P${p}: الإجابة المعتمدة لا تطابق مفتاح الملف`);
  if (q.skill === 'comparison') {
    const c = C[p]; assert.ok(c, 'لا تحقق للمقارنة P' + p);
    const want = c === 'd' ? 'd' : near(c[0], c[1]) ? 'c' : c[0] > c[1] ? 'a' : 'b';
    assert.equal(q.answer, want, 'P' + p);
  } else if (special[p]) {
    assert.equal(special[p](q), key, 'P' + p);
  } else {
    assert.ok(p in V, 'لا قيمة محسوبة للسؤال P' + p);
    const right = q.options.find(o => o.id === q.answer);
    const val = num(right.text);
    const rel = V[p] !== 0 ? Math.abs(val - V[p]) / Math.abs(V[p]) : Math.abs(val);
    // الأسئلة التقريبية (1140: «تقريبًا») تُقبل بالأقرب
    if (p === '1140') {
      const d = q.options.map(o => Math.abs(num(o.text) - V[p]));
      assert.equal(q.options[d.indexOf(Math.min(...d))].id, q.answer, 'P1140');
    } else {
      assert.ok(rel < 0.01, `P${p}: المحسوب ${V[p]} والخيار ${right.text}`);
      q.options.filter(o => o.id !== q.answer).forEach(o =>
        assert.ok(!(Math.abs(num(o.text) - V[p]) < 1e-9 && !/ط|س|ص|√/.test(o.text)), `P${p}: خيار آخر يساوي الإجابة (${o.text})`));
    }
  }
  n++;
}
